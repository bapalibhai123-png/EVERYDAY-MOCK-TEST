/* =========================================================
   SELECT ANSWER
========================================================= */

function selectAnswer(index) {

  userAnswers[currentQuestion] = index;

  renderTest();
}


/* =========================================================
   NEXT QUESTION
========================================================= */

function nextQuestion() {

  if (currentQuestion < currentTest.questions.length - 1) {

    currentQuestion++;

    renderTest();

  }
}


/* =========================================================
   PREVIOUS QUESTION
========================================================= */

function previousQuestion() {

  if (currentQuestion > 0) {

    currentQuestion--;

    renderTest();

  }
}


/* =========================================================
   QUESTION PALETTE
========================================================= */

function goToQuestion(index) {

  if (
    index < 0 ||
    index >= currentTest.questions.length
  ) {
    return;
  }

  currentQuestion = index;

  renderTest();
}


/* =========================================================
   TIMER
========================================================= */

function startTimer() {

  clearInterval(timerInterval);

  timerInterval = setInterval(() => {

    timerSeconds--;

    updateTimerDisplay();

    if (timerSeconds <= 0) {

      clearInterval(timerInterval);

      submitTest(true);

    }

  }, 1000);
}


/* =========================================================
   TIMER DISPLAY
========================================================= */

function updateTimerDisplay() {

  const timer = document.getElementById("timer");

  if (!timer) return;

  const minutes =
    Math.floor(timerSeconds / 60);

  const seconds =
    timerSeconds % 60;

  timer.textContent =
    String(minutes).padStart(2, "0") +
    ":" +
    String(seconds).padStart(2, "0");
}


/* =========================================================
   SUBMIT TEST
========================================================= */

function submitTest(autoSubmit = false) {

  if (!currentTest) return;

  if (!autoSubmit) {

    const unanswered =
      userAnswers.filter(answer => answer === null).length;

    if (unanswered > 0) {

      const confirmSubmit = confirm(
        `You have ${unanswered} unanswered question(s).\n\nAre you sure you want to submit?`
      );

      if (!confirmSubmit) {
        return;
      }

    } else {

      const confirmSubmit = confirm(
        "Are you sure you want to submit the test?"
      );

      if (!confirmSubmit) {
        return;
      }

    }

  }

  clearInterval(timerInterval);

  showResult();
}


/* =========================================================
   RESULT
========================================================= */

function showResult() {

  let correct = 0;
  let wrong = 0;
  let unanswered = 0;

  currentTest.questions.forEach((question, index) => {

    const answer = userAnswers[index];

    if (answer === null) {

      unanswered++;

    } else if (answer === question.correct) {

      correct++;

    } else {

      wrong++;

    }

  });

  const total = currentTest.questions.length;

  const percentage =
    ((correct / total) * 100).toFixed(2);


  let html = `

    <div class="result-wrapper">

      <div class="result-card">

        <div class="result-top">

          <h1>TEST COMPLETED</h1>

          <p>${currentTest.title}</p>

          <h3>
            Student:
            ${escapeHTML(studentName)}
          </h3>

        </div>


        <div class="score-box">

          <div>
            <strong>${correct}</strong>
            <span>Correct</span>
          </div>

          <div>
            <strong>${wrong}</strong>
            <span>Wrong</span>
          </div>

          <div>
            <strong>${unanswered}</strong>
            <span>Unanswered</span>
          </div>

          <div>
            <strong>${percentage}%</strong>
            <span>Score</span>
          </div>

        </div>


        <div class="result-actions">

          <button
            class="retry-btn"
            onclick="retryTest()"
          >
            RETRY TEST
          </button>

          <button
            class="home-btn"
            onclick="goHome()"
          >
            BACK TO HOME
          </button>

        </div>

      </div>


      <div class="review-section">

        <h2>Detailed Review</h2>

  `;


  currentTest.questions.forEach((question, index) => {

    const userAnswer = userAnswers[index];

    const isCorrect =
      userAnswer === question.correct;

    let status = "";

    if (userAnswer === null) {
      status = "Not Answered";
    } else if (isCorrect) {
      status = "Correct";
    } else {
      status = "Wrong";
    }


    html += `

      <div class="review-card">

        <div class="review-question">

          <strong>
            Q${index + 1}.
          </strong>

          ${escapeHTML(question.question)}

        </div>


        <div class="review-answer">

          <p>
            <strong>Your Answer:</strong>
            ${
              userAnswer === null
                ? "Not Answered"
                : String.fromCharCode(65 + userAnswer) +
                  ". " +
                  escapeHTML(question.options[userAnswer])
            }
          </p>


          <p>
            <strong>Correct Answer:</strong>
            ${String.fromCharCode(65 + question.correct)}.
            ${escapeHTML(question.options[question.correct])}
          </p>


          <p>
            <strong>Result:</strong>
            ${status}
          </p>


          <p class="explanation">

            <strong>Explanation:</strong>
            ${escapeHTML(question.explanation)}

          </p>

        </div>

      </div>

    `;

  });


  html += `

      </div>

    </div>

  `;


  document.getElementById("test-screen").innerHTML = html;

  /* Exit fullscreen after submission */

  if (
    document.fullscreenElement &&
    document.exitFullscreen
  ) {

    document.exitFullscreen().catch(() => {});

  }
}


/* =========================================================
   RETRY TEST
========================================================= */

function retryTest() {

  if (!currentTest) return;

  currentQuestion = 0;

  userAnswers =
    new Array(currentTest.questions.length).fill(null);

  timerSeconds =
    currentTest.duration * 60;

  renderTest();

  startTimer();

  if (document.documentElement.requestFullscreen) {

    document.documentElement
      .requestFullscreen()
      .catch(() => {});

  }
}


/* =========================================================
   BACK TO HOME
========================================================= */

function goHome() {

  clearInterval(timerInterval);

  if (
    document.fullscreenElement &&
    document.exitFullscreen
  ) {

    document.exitFullscreen().catch(() => {});

  }

  document.getElementById("test-screen").style.display = "none";

  document.getElementById("home-page").style.display = "block";

  updateTodayDate();
}


/* =========================================================
   SECURITY / HTML TEXT SAFETY
========================================================= */

function escapeHTML(text) {

  if (text === undefined || text === null) {
    return "";
  }

  return String(text)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}